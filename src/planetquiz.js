/** 그 행성의 문제 하나를 고른다 (바로 전에 낸 문제는 피한다). 보기는 섞는다 */
export function makePlanetProblem(zone) {
  const bank = PLANET_QUIZ[zone];
  if (!bank) return null;
  let i = Math.floor(Math.random() * bank.length);
  if (bank.length > 1 && i === lastAsked[zone]) i = (i + 1) % bank.length;
  lastAsked[zone] = i;
  const q = bank[i];
  const choices = [q.a, q.b, q.c].sort(() => Math.random() - 0.5);
  return { trivia: true, tier: 0, text: q.q, answer: q.a, choices, hint: q.why, groups: [] };
}
